#!/usr/bin/env bash
# Build the GitHub Pages site into dist-site/.
#
# The rendered MP4s are distributed through GitHub Releases (they are too large
# for git history and for a Pages artifact). The player loads them from the
# release URL configured below. To bundle local renders for a local preview,
# set SITE_INCLUDE_MEDIA=1 and the files in renders/ are copied into dist-site/media.
#
# Env:
#   RELEASE_TAG       release that hosts the MP4s (default: v0.1.0)
#   REPO_SLUG         owner/repo (default: rdrm95/masseffectrefuse)
#   SITE_INCLUDE_MEDIA=1  copy renders/*.mp4 into dist-site/media and point the player at them
set -euo pipefail
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT"
REPO_SLUG="${REPO_SLUG:-rdrm95/masseffectrefuse}"
RELEASE_TAG="${RELEASE_TAG:-v0.1.0}"
OUT="$ROOT/dist-site"

rm -rf "$OUT"
mkdir -p "$OUT/fonts" "$OUT/generated"

npx tsx scripts/export-site-data.ts
cp site/index.html site/styles.css site/player.js site/poster.jpg "$OUT/"
cp site/generated/* "$OUT/generated/"
cp public/fonts/Michroma-Regular.ttf public/fonts/Jura-Variable.ttf public/fonts/Exo2-Variable.ttf public/fonts/OFL-*.txt "$OUT/fonts/"
touch "$OUT/.nojekyll"

FILM_URL="https://github.com/$REPO_SLUG/releases/download/$RELEASE_TAG/MassEffectRefuse-Full.mp4"
TRAILER_URL="https://github.com/$REPO_SLUG/releases/download/$RELEASE_TAG/Trailer.mp4"
if [ "${SITE_INCLUDE_MEDIA:-0}" = "1" ]; then
  mkdir -p "$OUT/media"
  [ -f renders/MassEffectRefuse-Full.mp4 ] && cp renders/MassEffectRefuse-Full.mp4 "$OUT/media/" && FILM_URL="media/MassEffectRefuse-Full.mp4"
  [ -f renders/Trailer.mp4 ] && cp renders/Trailer.mp4 "$OUT/media/" && TRAILER_URL="media/Trailer.mp4"
fi

cat > "$OUT/config.js" <<EOF
// Generated by scripts/build-site.sh
window.REFUSE_MEDIA = {
  film: "$FILM_URL",
  trailer: "$TRAILER_URL",
  repo: "https://github.com/$REPO_SLUG",
  releases: "https://github.com/$REPO_SLUG/releases"
};
EOF
echo "Site built in $OUT (film: $FILM_URL)"
